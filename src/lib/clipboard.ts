/**
 * Copy text to the clipboard. The async Clipboard API needs a secure context
 * and a user gesture; where it is missing or refused, fall back to a hidden
 * textarea and execCommand, which older Safari and in-app browsers still
 * honour.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const area = document.createElement("textarea");
    area.value = text;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    let ok = false;
    try {
      ok = document.execCommand("copy");
    } catch {
      ok = false;
    }
    area.remove();
    return ok;
  }
}
